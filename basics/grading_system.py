#Exo 3 - grading system
number = int(input("Enter the number please: "))

if number >= 18 :
    print("Excellent")
elif number >= 16 :
    print("Alright")
elif number >= 14 :
    print("Good")
elif number >= 12 :
    print("Fairly Good")
elif number >= 10 :
    print("Average")
else :
    print("Failure")